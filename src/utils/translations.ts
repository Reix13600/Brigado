export function getTranslation(lang: LangType, key: string, vars?: Record<string, any>): string {
  let s = TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en[key] || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      s = s.replace(`{${k}}`, String(v));
    });
  }
  return s;
}
